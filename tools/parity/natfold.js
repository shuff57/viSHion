// Generates crates/core/src/natfold.rs from the real node ICU collator
// (Intl.Collator numeric + sensitivity base), the same collator js/ns.js natCompare uses.
// Run: node tools/parity/natfold.js
const fs = require('fs'), path = require('path');
const col = new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' });
const c = (a, b) => Math.sign(col.compare(a, b));
const letters = 'abcdefghijklmnopqrstuvwxyz', digits = '0123456789';
const pool = [];
for (const x of letters + digits) pool.push(x);
for (const x of letters) for (const y of letters) pool.push(x + y);
for (const x of letters) for (const y of letters) for (const z of letters) pool.push(x + y + z);
function eqOf(ch) {
  for (const p of pool) if (c(ch, p) === 0) return p;
  return null;
}
const modelOf = (ch) => ch.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase();
const E = [], P = [], N = [];
const posLetter = (ch) => { let l = null; for (const x of letters) if (c(x, ch) < 0) l = x; return l; };
const slots = {}; // letter -> [chars]
const nos = [];
for (let cp = 0xa0; cp <= 0x2ffff; cp++) {
  if (cp >= 0xd800 && cp < 0xe000) continue;
  const ch = String.fromCodePoint(cp);
  const latin = /\p{Script=Latin}/u.test(ch), nd = /\p{Nd}/u.test(ch), no = /\p{No}/u.test(ch);
  if (!latin && !nd && !no) continue;
  const model = modelOf(ch);
  const eq = eqOf(ch);
  if (nd) { if (eq && /^\d$/.test(eq) && model !== eq) E.push([ch, eq]); continue; }
  if (no) {
    if (eq && /^[a-z0-9]+$/.test(eq) && eq === model) { /* expands like the model does */ }
    if (c(ch, '0') < 0) N.push([ch, 2]); else if (c(ch, '9') > 0 && c(ch, 'a') < 0) nos.push(ch);
    continue;
  }
  if (eq !== null) { if (eq !== model || !/^[a-z0-9]+$/.test(model)) E.push([ch, eq]); continue; }
  const l = posLetter(ch);
  if (l === null) { if (c(ch, '0') < 0) N.push([ch, 2]); else nos.push(ch); continue; }
  (slots[l] = slots[l] || []).push(ch);
}
const PE = [];
for (const l of Object.keys(slots)) {
  const arr = slots[l].sort((a, b) => col.compare(a, b) || a.codePointAt(0) - b.codePointAt(0));
  let rank = 0, prev = null;
  for (const ch of arr) {
    if (prev !== null && c(prev, ch) !== 0) rank++;
    prev = ch;
    if (rank >= 998) throw new Error('slot overflow ' + l);
    PE.push([ch, 4, l.charCodeAt(0) * 1000 + 1 + rank]);
  }
}
{ const arr = nos.sort((a, b) => col.compare(a, b) || a.codePointAt(0) - b.codePointAt(0)); let rank = 0, prev = null;
  for (const ch of arr) { if (prev !== null && c(prev, ch) !== 0) rank++; prev = ch; PE.push([ch, 3, rank]); } }
for (const [ch] of N) { /* before digits: keep after ASCII symbols */ }
N.forEach(([ch], i) => PE.push([ch, 2, 0x1000 + ch.codePointAt(0)]));
const cp = (s) => s.codePointAt(0);
E.sort((a, b) => cp(a[0]) - cp(b[0])); PE.sort((a, b) => cp(a[0]) - cp(b[0]));
const hex = (n) => '0x' + n.toString(16).toUpperCase();
let out = '// @generated by tools/parity/natfold.js from node Intl.Collator(numeric, base). Do not edit.\n';
out += '//! Collation exceptions for `jsx::nat_compare`: characters whose base-level ICU weight is not what\n//! NFKD + mark stripping + lowercasing gives. Sorted by code point for binary search.\n\n';
out += '/// Characters ICU treats as the given ASCII letters/digits at base strength (`Đ`=`d`, `æ`=`ae`, `ß`=`ss`, ...).\npub static EXPAND: &[(char, &str)] = &[\n';
const BS = String.fromCharCode(92);
for (const [ch, e] of E) out += `    ('${BS}u{${cp(ch).toString(16)}}', "${e}"),\n`;
out += '];\n\n/// Characters with their own primary weight: (char, class, value). Class 4 sits between the ASCII letters\n/// (value = letter * 1000 + 1 + rank, so after that letter and before the next), class 3 after digits, class 2 symbols.\npub static OWN: &[(char, u8, u32)] = &[\n';
for (const [ch, k, v] of PE) out += `    ('${BS}u{${cp(ch).toString(16)}}', ${k}, ${v}),\n`;
out += '];\n';
fs.writeFileSync(path.join(__dirname, '..', '..', 'crates', 'core', 'src', 'natfold.rs'), out);
console.log('expand', E.length, 'own', PE.length);
