//! Generator for `src/hanfold.rs`; run with `cargo test -p vishion-core --test gen_han -- --ignored`
//! after `node tools/parity/han.js`. ICU4X orders Han ideographs by code point, node's ICU by
//! radical-stroke; this maps each Han char to the char ICU4X ranks where node ranks it.
use std::cmp::Ordering;
#[test]
#[ignore]
fn gen_han() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let j = std::fs::read_to_string(root.join("../../tools/parity/han_order.json")).unwrap();
    let groups: Vec<Vec<u32>> = serde_json::from_str(&j).unwrap();
    let node: Vec<u32> = groups.iter().map(|g| g[0]).collect();
    let s = |c: u32| char::from_u32(c).unwrap().to_string();
    let mut icu = node.clone();
    icu.sort_by(|a, b| match vishion_core::jsx::nat_compare_raw(&s(*a), &s(*b)) {
        Ordering::Equal => a.cmp(b),
        o => o,
    });
    let mut pairs: Vec<(u32, u32)> = node.iter().zip(icu.iter()).filter(|(a, b)| a != b).map(|(a, b)| (*a, *b)).collect();
    pairs.sort();
    // Runs: (start, len, mapped_start) with both sides consecutive.
    let mut runs: Vec<(u32, u32, u32)> = vec![];
    for (a, b) in pairs {
        if let Some(r) = runs.last_mut() {
            if a == r.0 + r.1 && b == r.2 + r.1 {
                r.1 += 1;
                continue;
            }
        }
        runs.push((a, 1, b));
    }
    let mut out = String::from("// @generated by tests/gen_han.rs from tools/parity/han.js (node Intl.Collator order). Do not edit.\n");
    out += "//! Han ideograph order: node's ICU (radical-stroke) vs ICU4X (code point). Each Han char is replaced by the\n//! char ICU4X ranks where node ranks it, so ICU4X's comparison then yields node's order.\n";
    out += "use std::borrow::Cow;\n\n/// (start, len, mapped_start), sorted by start.\nstatic RUNS: &[(u32, u32, u32)] = &[\n";
    for (a, l, b) in &runs {
        out += &format!("    (0x{:X}, {}, 0x{:X}),\n", a, l, b);
    }
    out += "];\n\nfn map(c: char) -> char {\n    let u = c as u32;\n    match RUNS.binary_search_by(|r| if u < r.0 { Ordering::Greater } else if u >= r.0 + r.1 { Ordering::Less } else { Ordering::Equal }) {\n        Ok(i) => char::from_u32(RUNS[i].2 + (u - RUNS[i].0)).unwrap_or(c),\n        Err(_) => c,\n    }\n}\n\nuse std::cmp::Ordering;\n\n";
    out += "pub fn fold(s: &str) -> Cow<'_, str> {\n    if s.chars().all(|c| (c as u32) < 0x2E80) {\n        return Cow::Borrowed(s);\n    }\n    Cow::Owned(s.chars().map(map).collect())\n}\n";
    std::fs::write(root.join("src/hanfold.rs"), out).unwrap();
    println!("runs {}", runs.len());
}
